"""Validate blake3_py + pearl_ref against vectors pinned in the Pearl repo.

  - seed.rs:30-39   SEED_SALT_A / SEED_SALT_B = blake3("pearl/cert-v3/noise-seed/{A,B}")
  - seed.rs:72-109  commitment_hash pinned vectors (Legacy and Salted), job_key=[0x11]*32,
                    hash_a=[0xAA]*32, hash_b=[0xBB]*32, new_for_tests(192, 320, 256) => m=192, n=320
  - pow_utils/commitment kernel: SEED_SALT_*_U32 little-endian words
  - known BLAKE3 answer: blake3(b"") = af1349b9...
"""
from blake3_py import blake3
from pearl_ref import SEED_SALT_A, SEED_SALT_B, commitment_hash

ok = True


def check(name, got, exp):
    global ok
    r = got == exp
    ok &= r
    print(f"[{'OK' if r else 'FAIL'}] {name}: {got.hex() if isinstance(got, bytes) else got}")


check("blake3(empty)", blake3(b""), bytes.fromhex("af1349b9f5f9a1a6a0404dea36dcc9499bcb25c9adc112b7cc9a93cae41f3262"))
# multi-chunk sanity (2049 bytes of 0..250 pattern, official test vector input pattern, len 2049)
inp = bytes(i % 251 for i in range(2049))
check("blake3(official len=2049)[:8]", blake3(inp)[:8].hex(), "5f4d72f40d7a5f82")

check("SEED_SALT_A", SEED_SALT_A, bytes([
    0x82, 0x49, 0x40, 0x6c, 0xa0, 0xed, 0x15, 0x16, 0x96, 0x16, 0xf6, 0x92, 0xfc, 0xf0, 0x76, 0xf8, 0x92, 0xdb, 0xdb, 0x2a, 0x70,
    0x23, 0xb8, 0x52, 0xf0, 0xd4, 0x77, 0x19, 0xc3, 0x90, 0x01, 0x7b]))
check("SEED_SALT_B", SEED_SALT_B, bytes([
    0x11, 0x30, 0x06, 0x32, 0xec, 0x63, 0x01, 0xca, 0x2b, 0xe2, 0xaf, 0x71, 0x8b, 0x3f, 0x4d, 0x4f, 0x1a, 0xe9, 0xc6, 0x39, 0x88,
    0xe8, 0xcc, 0x04, 0x48, 0x44, 0x30, 0x1d, 0x71, 0xb8, 0x9a, 0xa9]))

jk, ha, hb = bytes([0x11] * 32), bytes([0xAA] * 32), bytes([0xBB] * 32)
b, a = commitment_hash(jk, ha, hb, 192, 320, salted=False)
check("Legacy b_noise_seed", b, bytes([0xad, 0xd6, 0xf7, 0xea, 0x5f, 0xee, 0xbf, 0x89, 0xc8, 0xa7, 0x7e, 0x2e, 0xbf, 0xa0, 0xd8, 0x24, 0x42, 0xe7,
                                      0xdb, 0xb0, 0x04, 0x6d, 0xbd, 0x48, 0x97, 0x18, 0x61, 0xd1, 0x2f, 0xcb, 0x01, 0x77]))
check("Legacy a_noise_seed", a, bytes([0x48, 0x3b, 0x07, 0xb6, 0xf7, 0x31, 0x05, 0x03, 0x0b, 0x94, 0x82, 0x25, 0x5f, 0x37, 0x72, 0x3f, 0x3f, 0xed,
                                      0x69, 0xae, 0x91, 0x67, 0x24, 0xee, 0x82, 0x91, 0x84, 0x8b, 0x8c, 0x28, 0x79, 0x4b]))
b, a = commitment_hash(jk, ha, hb, 192, 320, salted=True)
check("Salted b_noise_seed", b, bytes([0x60, 0xed, 0x9b, 0x73, 0xc5, 0xa9, 0x59, 0x9b, 0x20, 0x0b, 0x6c, 0xd5, 0x63, 0xe7, 0xf0, 0xd5, 0xd9, 0xa6,
                                      0x7d, 0x24, 0x02, 0xd8, 0x5f, 0xd4, 0xef, 0x96, 0x6c, 0x58, 0x00, 0x80, 0xd0, 0xe5]))
check("Salted a_noise_seed", a, bytes([0x30, 0x17, 0x84, 0x16, 0x80, 0x05, 0xec, 0x83, 0x3a, 0xb0, 0xaa, 0x60, 0x00, 0x6f, 0x7f, 0xe7, 0xfa, 0xaa,
                                      0x95, 0x30, 0x7d, 0x8c, 0x1f, 0xc6, 0x81, 0x9b, 0x2f, 0xfd, 0xd7, 0x17, 0xec, 0xcf]))
# CUDA constant words (commitment_hash_from_merkle_roots_kernel.hpp:8-15) are the LE u32 view of the salts
words_a = [int.from_bytes(SEED_SALT_A[4 * i:4 * i + 4], "little") for i in range(8)]
check("SEED_SALT_A_U32[0..2]", [hex(w) for w in words_a[:2]], ["0x6c404982", "0x1615eda0"])
print("ALL OK" if ok else "SOME FAILED")
